use pwt::state::Selection;
use yew::prelude::*;
use yew::virtual_dom::Key;

use pwt::css::{Flex, Overflow};
use pwt::prelude::*;

use pwt::state::{use_selection, NavigationContainer};
use pwt::widget::nav::{Menu, MenuItem, NavigationDrawer};
use pwt::widget::{Column, Container, Pane, SelectionView, SelectionViewRenderInfo, SplitPane};

#[function_component]
pub fn NavigationDrawerDemo() -> Html {
    let content = use_state(|| html! {});

    let menu = Menu::new()
        .with_item(
            MenuItem::new("Entry 1")
                .key("id1")
                .icon_class("fa fa-paper-plane"),
        )
        .with_item(
            MenuItem::new("Submenu 1")
                .key("id2")
                .icon_class("fa fa-car")
                .submenu(
                    Menu::new()
                        .with_item(
                            MenuItem::new("Entry 2")
                                .key("id3")
                                .icon_class("fa fa-motorcycle"),
                        )
                        .with_item(
                            MenuItem::new("Entry 3")
                                .key("id4")
                                .icon_class("fa fa-bicycle"),
                        )
                        .with_item(
                            MenuItem::new("Submenu 2")
                                .key("id5")
                                .icon_class("fa fa-ship")
                                .submenu(
                                    Menu::new().with_item(
                                        MenuItem::new("Entry 4")
                                            .key("id6")
                                            .icon_class("fa fa-rocket"),
                                    ),
                                ),
                        ),
                ),
        )
        .with_spacer()
        .with_section_header("Section")
        .with_item(
            MenuItem::new("Submenu 3 (unselectable)")
                .key("unselectable")
                .selectable(false)
                .icon_class("fa fa-ship")
                .submenu(
                    Menu::new().with_item(
                        MenuItem::new("Entry 5")
                            .key("id7")
                            .icon_class("fa fa-rocket"),
                    ),
                ),
        )
        .with_item(MenuItem::new("Entry 6").key("id8"));

    let selection = use_selection(|| Selection::new());

    let drawer = NavigationDrawer::new(menu)
        .class(Overflow::Auto) // allow to shrink
        .router(true)
        .header(html! {<div class="pwt-p-2 pwt-font-size-title-large">{"Menu Header"}</div>})
        .selection(selection.clone())
        .border_start(true)
        .on_select({
            let content = content.clone();
            move |key: Option<Key>| {
                content.set(html! {<p>{format!("Selected key is {:?}", key)}</p>});
            }
        });

    let content1 = Column::new()
        .padding(2)
        .gap(4)
        .with_child(html! {
        <p>{"This view is generated by using the NavigationDrawer on_select() callback."}</p>})
        .with_child((&*content).clone());

    let content2 = Container::new()
        .padding(2)
        .with_child(
            SelectionView::new()
                .selection(selection)
                // add a default renderer
                .renderer(|event: &SelectionViewRenderInfo| {
                    Column::new()
                        .gap(4)
                        .with_child(html!{<p>{"This view is generated by SelectionView (default renderer)."}</p>})
                        .with_child(html!{<p>{format!("Selected key is {:?}", event.key)}</p>})
                        .into()
                })
                // use a special builder for "id1"
                .with_builder("id1", |_| {
                    html!{<p>{"This view is generated by the SelectionView builder for \"id1\""}</p>}
                })
        );

    NavigationContainer::new()
        .with_child(
            SplitPane::new()
                .class(Flex::Fill)
                .with_child(Pane::new(drawer).size(None))
                .with_child(Pane::new(content1).flex(1))
                .with_child(Pane::new(content2).flex(1)),
        )
        .into()
}
