use pwt::state::Selection;
use yew::prelude::*;
use yew::virtual_dom::Key;

use pwt::prelude::*;
use pwt::state::use_selection;

use pwt::widget::{Column, Container, Pane, SplitPane, SelectionView, SelectionViewRenderInfo};
use pwt::widget::nav::{NavMenu, NavMenuItem, NavigationDrawer};

#[function_component]
pub fn NavigationDemo() -> Html {

    let content = use_state(|| html!{});

    let menu = NavMenu::new()
       .with_item(
            NavMenuItem::new("Entry 1")
                .key("id1")
                .icon_class("fa fa-paper-plane")
        )
        .with_item(
            NavMenuItem::new("Submenu 1")
                .key("id2")
                .icon_class("fa fa-car")
                .submenu(
                    NavMenu::new()
                        .with_item(
                            NavMenuItem::new("Entry 2")
                                .key("id3")
                                .icon_class("fa fa-motorcycle")
                        )
                        .with_item(
                            NavMenuItem::new("Entry 3")
                                .key("id4")
                                .icon_class("fa fa-bicycle")
                        )
                        .with_item(
                            NavMenuItem::new("Submenu 2")
                                .key("id5")
                                .icon_class("fa fa-ship")
                                .submenu(
                                    NavMenu::new().with_item(
                                        NavMenuItem::new("Entry 4")
                                            .key("id6")
                                            .icon_class("fa fa-rocket")
                                    ),
                                ),
                        ),
                ),
        )
        .with_item(
            NavMenuItem::new("Submenu 3 (unselectable)")
                .key("unselectable")
                .selectable(false)
                .icon_class("fa fa-ship")
                .submenu(
                    NavMenu::new()
                        .with_item(
                            NavMenuItem::new("Entry 5")
                                .key("id7")
                                .icon_class("fa fa-rocket")
                        ),
                ),
        )
        .with_item(
            NavMenuItem::new("Entry 6")
                .key("id8")
        );

    let selection = use_selection(|| Selection::new());

    let drawer = NavigationDrawer::new(menu)
        .selection(selection.clone())
        .class("pwt-border-left")
        .on_select({
            let content = content.clone();
            move |key: Option<Key>| {
                content.set(html!{<p>{format!("Selected key is {:?}", key)}</p>});
            }
        })
        .navigation_container();


    let content1 = Column::new()
        .padding(2)
        .gap(4)
        .with_child(html!{
            <p>{"This view is generated by using the NavigationDrawer on_select() callback."}</p>})
        .with_child((&*content).clone());

    let content2 = Container::new()
        .padding(2)
        .with_child(
            SelectionView::new()
                .selection(selection)
                .renderer(|event: &SelectionViewRenderInfo| {
                    Column::new()
                        .gap(4)
                        .with_child(html!{<p>{"This view is generated by SelectionView (default renderer)."}</p>})
                        .with_child(html!{<p>{format!("Selected key is {:?}", event.key)}</p>})
                        .into()
                })
        );

    SplitPane::new()
            .class("pwt-fit")
            .with_child(Pane::new(drawer).size(None))
            .with_child(Pane::new(content1).flex(1))
            .with_child(Pane::new(content2).flex(1))
            .into()
}
